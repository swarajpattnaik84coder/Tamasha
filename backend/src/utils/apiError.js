class apiError extends Error{
    constructor(
        statusCode,
        message,
        errors = [],
        stack = ""
    ){
        super(message)
        this.statusCode = statusCode,
        this.data = null
        this.success = false
        this.errors = errors

        if(stack){
            this.stack = stack  // if stack trace is provided
        }
        else{
            Error.captureStackTrace(this,this.constructor)  // appends the stack trace generated by js to this class 
        }

    }
}

export {apiError}